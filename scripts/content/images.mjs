// Downloads every image referenced by the bundled content so the app works offline.
//
//   node scripts/content/images.mjs
//
// Markdown keeps the original URLs; data/image-index.ts maps each URL to a bundled asset, and
// src/components/MarkdownView.tsx renders the bundled file when there is one.
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DATA = path.join(ROOT, 'data');
const IMAGES = path.join(DATA, 'images');
const IMAGE_RE = /!\[[^\]]*\]\(([^)\s]+)[^)]*\)/g;
const FIELDS = ['conditionMd', 'descriptionRuMd', 'ideaRuMd'];

/** Stable, readable local name: <basename>-<short hash of the URL>.<ext> */
function localName(url) {
  const { pathname } = new URL(url);
  const ext = path.extname(pathname).toLowerCase();
  const base = path
    .basename(pathname, path.extname(pathname))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .slice(0, 40);
  const hash = crypto.createHash('sha1').update(url).digest('hex').slice(0, 8);
  return `${base}-${hash}${ext}`;
}

async function exists(file) {
  return fs.access(file).then(
    () => true,
    () => false,
  );
}

async function main() {
  const urls = new Set();
  for (const f of await fs.readdir(path.join(DATA, 'algos'))) {
    const json = JSON.parse(await fs.readFile(path.join(DATA, 'algos', f), 'utf8'));
    for (const field of FIELDS) for (const m of (json[field] ?? '').matchAll(IMAGE_RE)) urls.add(m[1]);
  }
  for (const f of await fs.readdir(path.join(DATA, 'theory'))) {
    const json = JSON.parse(await fs.readFile(path.join(DATA, 'theory', f), 'utf8'));
    for (const m of (json.bodyMd ?? '').matchAll(IMAGE_RE)) urls.add(m[1]);
  }

  await fs.mkdir(IMAGES, { recursive: true });
  const entries = [];
  const failed = [];
  for (const url of [...urls].sort()) {
    const name = localName(url);
    const file = path.join(IMAGES, name);
    if (!(await exists(file))) {
      const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (algo-master personal study app)' } });
      if (!res.ok) {
        failed.push(`${url} (HTTP ${res.status})`);
        continue;
      }
      await fs.writeFile(file, Buffer.from(await res.arrayBuffer()));
      console.log(`  downloaded ${name}`);
    }
    entries.push([url, name]);
  }

  // Drop files no longer referenced.
  const keep = new Set(entries.map(([, name]) => name));
  for (const f of await fs.readdir(IMAGES)) if (!keep.has(f)) await fs.rm(path.join(IMAGES, f));

  const index = `// Generated by scripts/content/images.mjs — do not edit by hand.
// Maps image URLs used in the content markdown to bundled copies, so images show offline.
export const bundledImages: Record<string, number> = {
${entries.map(([url, name]) => `  '${url}': require('./images/${name}'),`).join('\n')}
};
`;
  await fs.writeFile(path.join(DATA, 'image-index.ts'), index);
  console.log(`images=${entries.length} failed=${failed.length}`);
  if (failed.length) {
    console.log(failed.join('\n'));
    process.exitCode = 1;
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
