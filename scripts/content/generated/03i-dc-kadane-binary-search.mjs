// Классическое слияние двух отсортированных списков
function mergeTwo(a: ListNode | null, b: ListNode | null): ListNode | null {
  const dummy = new ListNode(0);
  let tail = dummy;

  while (a && b) {
    if (a.val <= b.val) {
      tail.next = a;
      a = a.next;
    } else {
      tail.next = b;
      b = b.next;
    }
    tail = tail.next;
  }

  // Остаток одного из списков пришиваем целиком
  tail.next = a ?? b;
  return dummy.next;
}

