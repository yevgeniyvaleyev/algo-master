function rotate(matrix: number[][]): void {
  const n = matrix.length;

  // 1. Транспонируем: меняем местами элементы относительно главной диагонали.
  //    Берём только j > i, иначе каждая пара поменялась бы дважды
  for (let i = 0; i < n; i++) {
    for (let j = i + 1; j < n; j++) {
      [matrix[i][j], matrix[j][i]] = [matrix[j][i], matrix[i][j]];
    }
  }

  // 2. Разворачиваем каждую строку — получаем поворот на 90° по часовой
  for (const row of matrix) {
    row.reverse();
  }
}

