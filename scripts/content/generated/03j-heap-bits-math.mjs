function findMaximizedCapital(k: number, w: number, profits: number[], capital: number[]): number {
  const n = profits.length;

  // Индексы проектов по возрастанию требуемого капитала
  const order = Array.from({ length: n }, (_, i) => i).sort((a, b) => capital[a] - capital[b]);

  // Max-куча прибылей проектов, которые уже по карману
  const available = new Heap<number>((a, b) => a > b);
  let next = 0; // первый ещё не открытый проект в order

  for (let round = 0; round < k; round++) {
    // Капитал вырос — открываем все проекты, которые теперь доступны
    while (next < n && capital[order[next]] <= w) {
      available.push(profits[order[next]]);
      next++;
    }

    // Делать нечего: ни один проект не доступен
    if (available.size() === 0) break;

    // Жадно берём самый прибыльный из доступных
    w += available.pop()!;
  }

  return w;
}

