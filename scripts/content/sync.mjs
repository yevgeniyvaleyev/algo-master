// Merges scraped LeetCode data into the bundled content and regenerates the seed.
//
//   node scripts/content/sync.mjs
//
// 1. scripts/out/problems/<slug>.json -> data/algos/<slug>.json
//    (scraped fields are refreshed, generated Russian fields are preserved)
// 2. scripts/out/plan.json -> data/manifest.json (seedVersion bumped when topics/algos change)
// 3. data/algos + data/theory -> data/content-index.ts (static requires for Metro)
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'scripts/out');
const DATA = path.join(ROOT, 'data');

const readJson = async (file) => JSON.parse(await fs.readFile(file, 'utf8'));
const writeJson = (file, value) => fs.writeFile(file, JSON.stringify(value, null, 2) + '\n');
const readJsonIfExists = (file) => readJson(file).catch(() => null);

/** Field order of data/algos/<slug>.json. */
const ALGO_KEYS = [
  'slug',
  'leetcodeId',
  'title',
  'difficulty',
  'group',
  'leetcodeUrl',
  'conditionMd',
  'descriptionRuMd',
  'solutionTs',
  'ideaRuMd',
  'theory',
];

async function main() {
  const plan = await readJson(path.join(OUT, 'plan.json'));
  await fs.mkdir(path.join(DATA, 'algos'), { recursive: true });

  // Theory titles shown on algorithms always come from the theory note itself.
  const theoryTitles = new Map();
  for (const f of await fs.readdir(path.join(DATA, 'theory'))) {
    if (!f.endsWith('.json')) continue;
    const t = await readJson(path.join(DATA, 'theory', f));
    theoryTitles.set(t.key, t.titleRu);
  }

  let imported = 0;
  const missing = [];
  for (const group of plan.groups) {
    for (const q of group.questions) {
      const scraped = await readJsonIfExists(path.join(OUT, 'problems', `${q.slug}.json`));
      if (!scraped) {
        missing.push(q.slug);
        continue;
      }
      const file = path.join(DATA, 'algos', `${q.slug}.json`);
      const existing = (await readJsonIfExists(file)) ?? {};
      const merged = {
        ...existing,
        slug: scraped.slug,
        leetcodeId: Number(scraped.frontendId),
        title: scraped.title,
        difficulty: scraped.difficulty,
        group: scraped.group,
        leetcodeUrl: scraped.leetcodeUrl,
        conditionMd: scraped.conditionMd,
      };
      if (merged.theory && theoryTitles.has(merged.theory.topicKey)) {
        merged.theory = { ...merged.theory, titleRu: theoryTitles.get(merged.theory.topicKey) };
      }
      const ordered = Object.fromEntries(ALGO_KEYS.filter((k) => merged[k] !== undefined).map((k) => [k, merged[k]]));
      await writeJson(file, ordered);
      imported++;
    }
  }

  // Manifest
  const topics = plan.groups.map((g) => ({ key: g.key, name: g.name, order: g.order }));
  const algos = [];
  for (const g of plan.groups) {
    for (const q of g.questions) {
      if (missing.includes(q.slug)) continue;
      algos.push({
        slug: q.slug,
        leetcodeId: Number(q.frontendId),
        title: q.title,
        difficulty: q.difficulty,
        topicKey: g.key,
        order: q.order,
        leetcodeUrl: `https://leetcode.com/problems/${q.slug}/`,
      });
    }
  }
  const contentHash = crypto.createHash('sha1').update(JSON.stringify({ topics, algos })).digest('hex').slice(0, 12);
  const previous = await readJsonIfExists(path.join(DATA, 'manifest.json'));
  const seedVersion = previous?.contentHash === contentHash ? previous.seedVersion : (previous?.seedVersion ?? 0) + 1;
  await writeJson(path.join(DATA, 'manifest.json'), { seedVersion, contentHash, topics, algos });

  // Content index
  const algoSlugs = (await fs.readdir(path.join(DATA, 'algos')))
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -5))
    .sort();
  const theoryKeys = (await fs.readdir(path.join(DATA, 'theory')))
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -5))
    .sort();
  const index = `// Generated by scripts/content/sync.mjs — do not edit by hand.
import type { AlgoContent, TheoryContent } from '../src/content/types';

export const algoLoaders: Record<string, () => AlgoContent> = {
${algoSlugs.map((s) => `  '${s}': () => require('./algos/${s}.json'),`).join('\n')}
};

export const theoryLoaders: Record<string, () => TheoryContent> = {
${theoryKeys.map((k) => `  '${k}': () => require('./theory/${k}.json'),`).join('\n')}
};
`;
  await fs.writeFile(path.join(DATA, 'content-index.ts'), index);

  console.log(
    `imported=${imported} missing=${missing.length} topics=${topics.length} algos=${algos.length} seedVersion=${seedVersion}`,
  );
  if (missing.length) console.log('Not scraped yet:', missing.join(', '));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
